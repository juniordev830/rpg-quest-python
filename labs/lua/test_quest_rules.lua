local quest = dofile("labs/lua/quest_rules.lua")
local normal = assert(quest.reward(5, 3, false))
assert(normal.experience == 60 and normal.gold == 9)
local boss = assert(quest.reward(5, 3, true))
assert(boss.experience == 310 and boss.gold == 34)
local result, err = quest.reward(0, 1, false)
assert(result == nil and err:find("level"))
result, err = quest.reward(2, -1, false)
assert(result == nil and err:find("monsters"))
print("Lua quest checks passed")
